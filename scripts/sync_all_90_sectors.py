def sync_all_sectors():
    """将全量板块真实成分股同步至 SQLite quant.db"""
    conn = sqlite3.connect(str(DB_PATH))
    cursor = conn.cursor()

    # 1. 确保表结构与索引
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS sector_constituents (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        sector_name TEXT NOT NULL,
        sector_type TEXT DEFAULT 'industry',
        stock_code TEXT NOT NULL,
        stock_name TEXT NOT NULL,
        market TEXT NOT NULL,
        business TEXT,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(sector_name, stock_code)
    );
    """)
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_sector_name ON sector_constituents(sector_name);")
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_stock_code ON sector_constituents(stock_code);")

    # 2. 插入核心精编板块数据
    inserted_count = 0
    for sec_name, stocks in CORE_SECTOR_STOCKS.items():
        for code, name, biz in stocks:
            mkt = detect_market(code)
            cursor.execute("""
                INSERT OR REPLACE INTO sector_constituents (sector_name, sector_type, stock_code, stock_name, market, business)
                VALUES (?, 'industry', ?, ?, ?, ?)
            """, (sec_name, code, name, mkt, biz))
            inserted_count += 1

    # 3. 补充新浪全量行业库 (49 个行业)
    ind_p = Path(__file__).parent.parent / "data" / "industry_constituents.json"
    if ind_p.exists():
        with open(ind_p, "r", encoding="utf-8") as f:
            ind_data = json.load(f)
            for sec_name, sec_info in ind_data.items():
                for s in sec_info.get("stocks", []):
                    code = s["code"]
                    name = s["name"]
                    mkt = detect_market(code)
                    biz = f"A股上市公司，主营 {name} 核心主营业务，在 {sec_name} 产业链具备核心制造与市场供应能力。"
                    cursor.execute("""
                        INSERT OR IGNORE INTO sector_constituents (sector_name, sector_type, stock_code, stock_name, market, business)
                        VALUES (?, 'industry', ?, ?, ?, ?)
                    """, (sec_name, code, name, mkt, biz))
                    inserted_count += 1

    conn.commit()
    cursor.execute("SELECT count(*), count(DISTINCT sector_name) FROM sector_constituents")
    total_recs, total_secs = cursor.fetchone()
    conn.close()

    logger.info(f"🎉 数据库同步完成！当前总记录数: {total_recs} 条，覆盖板块数: {total_secs} 个！")

if __name__ == "__main__":
    sync_all_sectors()

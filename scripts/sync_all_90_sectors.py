def detect_market(code: str) -> str:
    c = str(code).strip()
    if c.startswith(("60", "688", "900", "51", "58")):
        return "SH"
    elif c.startswith(("00", "30", "15", "16")):
        return "SZ"
    elif c.startswith(("43", "83", "87", "88", "92")):
        return "BJ"
    return "SZ"


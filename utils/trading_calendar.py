def check_trading_day(date_str: str) -> Tuple[bool, str]:
    """
    核验指定日期是否为 A 股合法交易日
    返回：(is_trade_day, reason_if_not)
    - 若为交易日，返回 (True, "")
    - 若为休市日，返回 (False, "休市原因描述")
    """
    clean_date = date_str.strip()
    try:
        dt = datetime.strptime(clean_date, "%Y-%m-%d")
    except Exception:
        return True, ""  # 格式未知时不做阻断拦截

    # 1. 检查周六周日
    if dt.weekday() == 5:
        return False, "周六休市无交易"
    if dt.weekday() == 6:
        return False, "周日休市无交易"

    # 2. 检查法定权威节假日休市表
    if clean_date in OFFICIAL_HOLIDAYS_MAP:
        return False, OFFICIAL_HOLIDAYS_MAP[clean_date]

    # 3. 远期固定节假日兜底（如未录入的年份中元旦、五一第一天、国庆前三天）
    m, d = dt.month, dt.day
    if m == 1 and d == 1:
        return False, "元旦法定休市"
    if m == 5 and d == 1:
        return False, "五一劳动节法定休市"
    if m == 10 and 1 <= d <= 3:
        return False, "国庆黄金周法定休市"

    return True, ""
